import { expect, test } from '@playwright/test'
import { cell, center, emptyRecords, item, openApp, restore } from './browser-fixtures'

test('인접 월 일정의 빠른 추가와 카테고리 변경, Todo 편집·이동', async ({ page }) => {
  await openApp(page)
  await restore(page, emptyRecords())
  const neighbor = cell(page, '2026-09-01')
  const neighborBox = (await neighbor.boundingBox())!
  await neighbor.click({ position: { x: neighborBox.width - 6, y: neighborBox.height - 6 } })
  await page.getByRole('button', { name: '일정 추가' }).click()
  const title = page.getByLabel('제목')
  await expect(title).toBeFocused()
  await title.fill('인접 월 일정')
  await title.press('Enter')
  await page.getByRole('dialog').getByRole('button', { name: '닫기' }).click()
  const event = neighbor.getByRole('button', { name: '인접 월 일정' })
  await event.click({ button: 'right' })
  await page.getByRole('dialog', { name: '카테고리 변경' }).getByRole('button', { name: '프로젝트' }).click()
  await expect(event).toHaveCSS('border-left-color', 'rgb(121, 81, 188)')
  await event.click()
  await page.getByLabel('완료', { exact: true }).check()
  await page.getByLabel('제목').fill('수정된 일정')
  await page.getByRole('button', { name: '저장' }).click()
  await expect(neighbor.getByRole('button', { name: '수정된 일정' })).toHaveAttribute('data-completed', 'true')

  await page.getByRole('button', { name: '할 일 목록' }).click()
  await page.getByRole('button', { name: '할 일 추가' }).click()
  await title.fill('자료 정리')
  await page.getByLabel('카테고리').selectOption('category-3')
  await title.press('Enter')
  const todo = page.getByRole('complementary', { name: '할 일' })
  await todo.getByRole('button', { name: '자료 정리 완료' }).click()
  await expect(todo.getByRole('button', { name: '자료 정리 완료' })).toHaveAttribute('aria-pressed', 'true')
  await todo.getByRole('button', { name: '자료 정리 달력으로 이동' }).click()
  await page.keyboard.press('Escape')
  await expect(todo.getByRole('button', { name: '자료 정리', exact: true })).toBeVisible()

  const handle = await center(todo.getByRole('button', { name: '자료 정리 달력으로 이동' }))
  const targetCell = cell(page, '2026-08-18')
  const target = await center(targetCell)
  await page.mouse.move(handle.x, handle.y)
  await page.mouse.down()
  await page.mouse.move(handle.x - 20, handle.y - 20, { steps: 3 })
  await page.mouse.move(target.x, target.y, { steps: 12 })
  await expect(targetCell).toHaveAttribute('data-over', 'true')
  await page.mouse.up()
  const scheduled = targetCell.getByRole('button', { name: '자료 정리' })
  await expect(page.locator('[data-placement]')).toHaveText(/8월 18일.*배치했어요/)
  await expect(scheduled).toHaveAttribute('data-completed', 'true')
  await expect(scheduled).toHaveCSS('border-left-color', 'rgb(121, 81, 188)')
  await scheduled.click()
  await expect(page.getByLabel('시간 지정')).not.toBeChecked()
  await page.getByRole('button', { name: '삭제' }).click()
  await expect(scheduled).toHaveCount(0)
})

test('주 시작 변경, 인접 월 일정과 오프라인 앱 셸', async ({ page, context, browserName }) => {
  await openApp(page, '2021-02-18T12:00:00')
  const records = emptyRecords()
  records.items.push(item('경계 일정', '2021-03-01'))
  await restore(page, records)
  const grid = page.locator('[data-weeks]')
  await expect(grid).toHaveAttribute('data-weeks', '4')
  await page.getByRole('button', { name: '설정', exact: true }).click()
  await page.getByLabel('주 시작 요일').selectOption('0')
  await page.getByRole('button', { name: '닫기' }).click()
  await expect(grid).toHaveAttribute('data-weeks', '5')
  await expect(cell(page, '2021-03-01').getByText('경계 일정')).toBeVisible()

  if (browserName === 'chromium') {
    await page.evaluate(() => navigator.serviceWorker.ready)
    await page.reload()
    await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller))
    await context.setOffline(true)
    await page.reload()
    await expect(cell(page, '2021-03-01').getByText('경계 일정')).toBeVisible()
    await page.getByRole('button', { name: '할 일 목록' }).click()
    await page.getByRole('button', { name: '할 일 추가' }).click()
    await page.getByLabel('제목').fill('오프라인 할 일')
    const savedTodo = page.getByRole('button', { name: '오프라인 할 일', exact: true })
    await page.getByRole('button', { name: '저장' }).click()
    await expect(savedTodo).toBeVisible()
    await context.setOffline(false)
    await page.reload()
    await page.getByRole('button', { name: '할 일 목록' }).click()
    await expect(savedTodo).toBeVisible()
  }
})

test('글자 크기와 카테고리 순서가 다시 열어도 적용된다', async ({ page }) => {
  await openApp(page)
  const records = emptyRecords()
  records.items.push(item('글자 크기 확인', '2026-08-18'), item('읽을 책', null))
  records.items.push(...Array.from({ length: 8 }, (_, index) => item(`추가 일정 ${index + 1}`, '2026-08-18', index + 1)))
  await restore(page, records)

  await page.getByRole('button', { name: '설정', exact: true }).click()
  const settings = page.getByRole('dialog', { name: '설정' })
  await settings.getByRole('button', { name: '공부 위로', exact: true }).click()
  await expect(settings.getByLabel('카테고리', { exact: true }).locator('option').first()).toHaveText('공부')
  await settings.getByLabel('달력 일정 글자 크기').selectOption('14')
  await expect(settings.getByLabel('달력 일정 글자 크기')).toHaveValue('14')
  await settings.getByLabel('할 일 글자 크기').selectOption('18')
  await expect(settings.getByLabel('할 일 글자 크기')).toHaveValue('18')
  await settings.getByRole('button', { name: '자주', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'plum')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'plum')

  const event = cell(page, '2026-08-18').getByRole('button', { name: '글자 크기 확인' })
  await expect(event).toHaveCSS('font-size', '14px')
  await event.click({ button: 'right' })
  const choices = page.getByRole('dialog', { name: '카테고리 변경' })
  await expect(choices.getByRole('button').first()).toHaveText('공부')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '할 일 목록' }).click()
  await expect(page.getByRole('button', { name: '읽을 책', exact: true })).toHaveCSS('font-size', '18px')

  if (page.viewportSize()!.width < 760) {
    const visible = cell(page, '2026-08-18').locator('[data-event]')
    const previous = await visible.count()
    await page.getByRole('button', { name: '설정', exact: true }).click()
    await settings.getByLabel('달력 일정 글자 크기').selectOption('10')
    await settings.getByRole('button', { name: '닫기' }).click()
    await expect(event).toHaveCSS('font-size', '10px')
    expect(await visible.count()).toBeGreaterThan(previous)
  }
})
