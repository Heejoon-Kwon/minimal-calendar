test('인접 월 일정의 빠른 추가와 카테고리 변경, Todo 편집·이동', async ({ page }) => {
  await openApp(page)
  await restore(page, emptyRecords())
  const neighbor = cell(page, '2026-09-01')
  const neighborBox = (await neighbor.boundingBox())!
  await neighbor.click({ position: { x: neighborBox.width - 6, y: neighborBox.height - 6 } })
  const title = page.getByLabel('제목')
  await expect(title).toBeFocused()
  await title.fill('인접 월 일정')
  await title.press('Enter')
  const event = neighbor.getByRole('button', { name: '인접 월 일정' })
  await event.click({ button: 'right' })
  await page.getByRole('dialog', { name: '카테고리 변경' }).getByRole('button', { name: '프로젝트' }).click()
  await expect(event).toHaveCSS('border-left-color', 'rgb(121, 81, 188)')
  await event.click()
  await expect(page.getByLabel('완료', { exact: true })).toHaveCount(0)
  await page.getByLabel('제목').fill('수정된 일정')
  await page.getByRole('button', { name: '저장' }).click()
  await expect(neighbor.getByRole('button', { name: '수정된 일정' })).toBeVisible()

  await page.getByRole('button', { name: '미정 일정 목록' }).click()
  await page.getByRole('button', { name: '미정 일정 추가' }).click()
  await title.fill('자료 정리')
  await page.getByLabel('카테고리').selectOption('category-3')
  await title.press('Enter')
  const todo = page.getByRole('complementary', { name: '미정 일정' })
  await todo.getByRole('button', { name: '자료 정리 달력으로 이동' }).press('Enter')
  await page.keyboard.press('Escape')
  await expect(todo.getByRole('button', { name: '자료 정리', exact: true })).toBeVisible()

  const backlogItem = todo.getByRole('button', { name: '자료 정리', exact: true })
  const targetCell = cell(page, '2026-08-18')
  const target = await center(targetCell)
  await startMouseDrag(page, backlogItem)
  await page.mouse.move(target.x, target.y, { steps: 12 })
  await expect(targetCell).toHaveAttribute('data-over', 'true')
  await page.mouse.up()
  const scheduled = targetCell.getByRole('button', { name: '자료 정리' })
  await expect(page.locator('[data-placement]')).toHaveText(/8월 18일.*배치했어요/)
  await expect(scheduled).toBeVisible()
  await expect(scheduled).toHaveCSS('border-left-color', 'rgb(121, 81, 188)')
  await scheduled.click()
  await expect(page.getByLabel('시간 지정')).not.toBeChecked()
  await page.keyboard.press('Escape')

  const nextCell = cell(page, '2026-08-19')
  const next = await center(nextCell)
  await startMouseDrag(page, scheduled)
  await page.mouse.move(next.x, next.y, { steps: 5 })
  await expect(nextCell).toHaveAttribute('data-over', 'true')
  await page.mouse.up()
  const moved = nextCell.getByRole('button', { name: '자료 정리' })
  await expect(moved).toBeVisible()
  await expect(scheduled).toHaveCount(0)
  await startMouseDrag(page, moved)
  const unschedule = await center(page.getByText('미정 일정 목록에 놓기', { exact: true }))
  await page.mouse.move(unschedule.x, unschedule.y)
  await page.mouse.up()
  await expect(backlogItem).toBeVisible()
  await expect(moved).toHaveCount(0)
  await startMouseDrag(page, backlogItem)
  await page.mouse.move(target.x, target.y)
  await page.mouse.up()
  await scheduled.click({ button: 'right' })
  const menu = page.getByRole('dialog', { name: '카테고리 변경' })
  await expect(menu.getByRole('button').last()).toHaveText('삭제')
  await menu.getByRole('button', { name: '삭제' }).click()
  await expect(scheduled).toHaveCount(0)
})

test('주 시작 변경, 인접 월 일정과 오프라인 앱 셸', async ({ page, context, browserName }) => {
  await openApp(page, '2021-02-18T12:00:00')
  const records = emptyRecords()
  records.items.push(item('경계 일정', '2021-03-01'))
  await restore(page, records)
  const grid = page.locator('[data-weeks]')
  await expect(grid).toHaveAttribute('data-weeks', '4')
  await page.getByRole('button', { name: '설정', exact: true }).click()
  await page.getByLabel('주 시작 요일').selectOption('0')
  await page.getByRole('button', { name: '닫기' }).click()
  await expect(grid).toHaveAttribute('data-weeks', '5')
  await expect(cell(page, '2021-03-01').getByText('경계 일정')).toBeVisible()

  if (browserName === 'chromium') {
    await page.evaluate(() => navigator.serviceWorker.ready)
    await page.reload()
    await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller))
    await context.setOffline(true)
    await page.reload()
    await expect(cell(page, '2021-03-01').getByText('경계 일정')).toBeVisible()
    await page.getByRole('button', { name: '미정 일정 목록' }).click()
    await page.getByRole('button', { name: '미정 일정 추가' }).click()
    await page.getByLabel('제목').fill('오프라인 할 일')
    const savedTodo = page.getByRole('button', { name: '오프라인 할 일', exact: true })
    await page.getByRole('button', { name: '저장' }).click()
    await expect(savedTodo).toBeVisible()
    await context.setOffline(false)
    await page.reload()
    await page.getByRole('button', { name: '미정 일정 목록' }).click()
    await expect(savedTodo).toBeVisible()
  }
})

test('날짜를 누르거나 같은 칸에서 놓으면 단일 일정, 다른 칸에서 놓으면 기간 일정', async ({ page }) => {
  await openApp(page)
  const start = cell(page, '2026-08-18')
  const finish = cell(page, '2026-08-20')
  const editor = page.getByRole('dialog', { name: '일정 추가' })
  const title = editor.getByLabel('제목')
  await start.locator('[data-day-trigger]').click()
  await expect(title).toBeFocused()
  await expect(editor).toContainText('8월 18일')
  await expect(editor).not.toContainText('~')
  await title.fill('한 번 눌러 등록')
  await title.press('Enter')
  await expect(start.getByRole('button', { name: '한 번 눌러 등록' })).toHaveAttribute('data-range-event', 'false')

  const origin = await center(start.locator('[data-day-trigger]'))
  const destination = await center(finish.locator('[data-day-trigger]'))
  await page.mouse.move(origin.x, origin.y)
  await page.mouse.down()
  await expect(start).toHaveAttribute('data-range-preview', 'false')
  await page.mouse.up()
  await expect(editor).toContainText('8월 18일')
  await expect(editor).not.toContainText('~')
  await editor.getByRole('button', { name: '닫기' }).click()

  await page.mouse.move(destination.x, destination.y)
  await page.mouse.down()
  await page.mouse.move(origin.x, origin.y, { steps: 5 })
  await expect(finish).toHaveAttribute('data-range-preview', 'true')
  await expect(start).toHaveAttribute('data-range-preview', 'true')
  await page.mouse.up()
  await expect(editor).toContainText(/8월 18일.*~.*8월 20일/)
  await title.fill('거꾸로 끈 기간')
  await title.press('Enter')
  await expect(page.locator('[data-range-event="true"]').filter({ hasText: '거꾸로 끈 기간' })).toHaveCount(1)
})

