test('미정 목록을 Alt+E로 열거나 설정에서 단축키를 변경한다', async ({ page }) => {
  await openApp(page)
  const trigger = page.getByRole('button', { name: '미정 일정 목록' })
  const panel = page.getByRole('complementary', { name: '미정 일정' })
  const lowerToday = cell(page, '2026-08-18')
  const upperToday = cell(page, '2026-08-04')
  const calendar = page.getByRole('region', { name: '월간 달력' })
  const calendarBox = (await calendar.boundingBox())!
  expect((await trigger.boundingBox())!.y).toBeGreaterThanOrEqual(calendarBox.y + calendarBox.height)

  await expect(trigger).toHaveAttribute('aria-keyshortcuts', 'Alt+E')
  await page.keyboard.press('Alt+e')
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(trigger).toBeFocused()
  await expect(panel).toHaveAttribute('data-side', 'top')
  const topPanel = (await panel.boundingBox())!
  expect(topPanel.y + topPanel.height).toBeLessThan((await lowerToday.boundingBox())!.y)

  await page.keyboard.press('Alt+e')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(panel).toHaveCount(0)

  await page.clock.setFixedTime(new Date('2026-08-04T12:00:00'))
  await page.getByRole('button', { name: '오늘', exact: true }).click()
  await trigger.click()
  await expect(panel).toHaveAttribute('data-side', 'bottom')
  const topToday = (await upperToday.boundingBox())!
  expect((await panel.boundingBox())!.y).toBeGreaterThan(topToday.y + topToday.height)
  await page.keyboard.press('Escape')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')

  await page.getByRole('button', { name: '설정', exact: true }).click()
  await page.getByLabel('미정 목록 단축키').selectOption('K')
  await page.getByRole('button', { name: '닫기' }).click()
  await expect(trigger).toHaveAttribute('aria-keyshortcuts', 'Alt+K')
  await page.reload()
  await expect(trigger).toHaveAttribute('aria-keyshortcuts', 'Alt+K')
  await page.keyboard.press('Alt+e')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await page.keyboard.press('Alt+k')
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await page.getByRole('button', { name: '2주', exact: true }).click()
  const plannerTrigger = page.getByRole('button', { name: '미정 할 일 목록' })
  await expect(plannerTrigger).toHaveAttribute('aria-keyshortcuts', 'Alt+K')
  await page.keyboard.press('Alt+k')
  await expect(plannerTrigger).toHaveAttribute('aria-expanded', 'true')
})

