import { expect, it } from 'vitest'
import { fromKey } from '../src/calendar'
import { koreanHoliday } from '../src/data/holidays'

it.each([
  ['2026-02-16', '설날'],
  ['2026-02-18', '설날'],
  ['2026-03-02', '대체공휴일(3·1절)'],
  ['2026-05-01', '노동절'],
  ['2026-05-25', '대체공휴일(부처님오신날)'],
  ['2026-06-03', '전국동시지방선거'],
  ['2026-06-08', undefined],
  ['2026-07-17', '제헌절'],
  ['2026-08-17', '대체공휴일(광복절)'],
  ['2026-09-26', '추석'],
  ['2026-09-28', undefined],
  ['2027-02-09', '대체공휴일(설날)'],
  ['2027-05-03', '대체공휴일(노동절)'],
  ['2027-07-19', '대체공휴일(제헌절)'],
  ['2025-07-17', undefined],
])('대한민국 공휴일 %s', (date, name) => {
  expect(koreanHoliday(fromKey(date))).toBe(name)
})
