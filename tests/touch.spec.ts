import { expect, test } from '@playwright/test'
import { cell, center, emptyRecords, item, openApp, restore } from './browser-fixtures'

test('하단 스와이프로 할 일 열기, 길게 눌러 날짜에 배치하기', async ({ page, context, browserName, hasTouch }) => {
  test.skip(browserName !== 'chromium' || !hasTouch)
  await openApp(page)
  const records = emptyRecords()
  records.items.push(item('터치 작업', null))
  await restore(page, records)
  const cdp = await context.newCDPSession(page)
  const trigger = page.getByRole('button', { name: '미정 일정 목록' })
  const dock = (await page.locator('[data-dock-pull]').boundingBox())!
  const grip = { x: dock.x + 15, y: dock.y + dock.height / 2 }
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [grip] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: grip.x, y: grip.y - 78 }] })
  await expect(page.locator('#todo-panel')).toHaveAttribute('data-pulling', 'true')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')

  const todo = page.getByRole('button', { name: '터치 작업', exact: true })
  const source = await center(todo)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [source] })
  await expect(page.getByRole('button', { name: '이동 취소' })).toBeVisible()
  const selected = cell(page, '2026-08-18')
  const target = await center(selected)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [target] })
  await expect(selected).toHaveAttribute('data-over', 'true')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  const event = selected.getByRole('button', { name: '터치 작업' })
  const eventPoint = await center(event)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [eventPoint] })
  await expect(page.getByRole('button', { name: '이동 취소' })).toBeVisible()
  const next = cell(page, '2026-08-19')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [await center(next)] })
  await expect(next).toHaveAttribute('data-over', 'true')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(next.getByRole('button', { name: '터치 작업' })).toBeVisible()

  const startDay = cell(page, '2026-08-20')
  const finishDay = cell(page, '2026-08-25')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [await center(startDay)] })
  await expect(startDay).toHaveAttribute('data-range-preview', 'true')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [await center(finishDay)] })
  await expect(finishDay).toHaveAttribute('data-range-preview', 'true')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  const editor = page.getByRole('dialog', { name: '일정 추가' })
  await expect(editor).toContainText('8월 20일')
  await expect(editor).toContainText('8월 25일')
  await editor.getByLabel('제목').fill('연속 휴가')
  await editor.getByRole('button', { name: '저장' }).tap()
  await expect(page.locator('[data-range-event="true"]').filter({ hasText: '연속 휴가' })).toHaveCount(2)

  const sameDate = cell(page, '2026-08-26').locator('[data-day-trigger]')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [await center(sameDate)] })
  await expect(cell(page, '2026-08-26')).toHaveAttribute('data-range-preview', 'true')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(editor).toContainText('8월 26일')
  await expect(editor).not.toContainText('~')
})

test('달력 좌우 스와이프로 연도 경계를 넘나들고 일정 탭과 구분한다', async ({ page, context }) => {
  await openApp(page, '2026-12-18T12:00:00')
  const records = emptyRecords()
  records.items.push(item('스와이프 확인', '2026-12-18'))
  await restore(page, records)
  const cdp = await context.newCDPSession(page)
  async function swipe(point: { x: number; y: number }, dx: number, dy = 0) {
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [point] })
    for (const step of [1 / 3, 2 / 3, 1]) {
      await cdp.send('Input.dispatchTouchEvent', {
        type: 'touchMove', touchPoints: [{ x: point.x + dx * step, y: point.y + dy * step }],
      })
    }
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  }

  const event = page.getByRole('button', { name: '스와이프 확인', exact: true })
  const editor = page.getByRole('dialog', { name: '항목 편집' })
  await event.tap()
  await expect(editor).toBeVisible()
  await editor.getByRole('button', { name: '닫기' }).tap()
  await swipe(await center(event), -130)
  await expect(page.getByRole('heading', { name: '2027년 1월' })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await swipe(await center(cell(page, '2027-01-06')), 130)
  await expect(page.getByRole('heading', { name: '2026년 12월' })).toBeVisible()
  await expect.poll(() => page.locator('[data-weeks]').evaluate(grid => grid.getAnimations().length)).toBe(0)
  await swipe(await center(cell(page, '2026-12-16')), 16, 75)
  await expect(page.getByRole('heading', { name: '2026년 12월' })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await event.tap()
  await expect(page.getByRole('dialog', { name: '항목 편집' })).toBeVisible()
})

test('미정 할 일을 손가락으로 옮기고 놓기 전에는 날짜를 변경하지 않는다', async ({ page, context }) => {
  await openApp(page)
  const records = emptyRecords()
  records.items.push({ ...item('터치로 배정', null), planner_todo: true })
  await restore(page, records)
  await page.getByRole('button', { name: '2주', exact: true }).tap()
  await page.getByRole('button', { name: '미정 할 일 목록' }).tap()
  const task = page.getByRole('button', { name: '터치로 배정', exact: true })
  const first = page.locator('[data-planner-date="2026-08-17"]')
  const second = page.locator('[data-planner-date="2026-08-18"]')
  const cdp = await context.newCDPSession(page)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [await center(task)] })
  await expect(page.locator('[data-drag-preview]')).toHaveText('터치로 배정')
  const cancel = page.getByRole('button', { name: '이동 취소' })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [await center(cancel)] })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(task).toBeVisible()

  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [await center(task)] })
  await expect(page.locator('[data-drag-preview]')).toHaveText('터치로 배정')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [await center(first.getByRole('heading'))] })
  await expect(first).toHaveAttribute('data-over', 'true')
  await expect(first.getByText('터치로 배정')).toHaveCount(0)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [await center(second.getByRole('heading'))] })
  await expect(second).toHaveAttribute('data-over', 'true')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(second.getByRole('button', { name: '터치로 배정', exact: true })).toBeVisible()
  await expect(first.getByText('터치로 배정')).toHaveCount(0)
})
